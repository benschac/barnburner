// Index the documentation the installed XState packages ship.
// xstate ships its docs under docs/ and @xstate/effect ships a README, both at
// the version the lockfile pins, so this writes two indexes and copies nothing.
// It reads only local files.
//
//   node scripts/index-xstate-docs.mjs           write .agent-sources/xstate/index.md and xstate-effect/index.md
//   node scripts/index-xstate-docs.mjs --check   fail when either file does not match the installed packages

import { NodeRuntime, NodeServices } from '@effect/platform-node'
import { Array, Effect, FileSystem, Option, Order, Path, Schema } from 'effect'
import { Command, Flag } from 'effect/cli'
import { loggerLayer } from '../lib/logger.mjs'

class XStateNotInstalled extends Schema.TaggedError()('XStateNotInstalled', {
  name: Schema.String,
  message: Schema.String,
}) {}

class StaleXStateIndex extends Schema.TaggedError()('StaleXStateIndex', {
  files: Schema.Array(Schema.String),
  message: Schema.String,
}) {}

// The workspace that pins XState; bun may install its packages there or hoist them to the root.
const owner = 'apps/web'
const escapeCell = (text) => text.replaceAll('|', '\\|')

// A page's frontmatter value, unquoted, or none.
const frontmatter = (lines, key) => {
  if (lines[0] !== '---') return Option.none()
  const end = lines.indexOf('---', 1)
  return Array.findFirst(lines.slice(1, end), (line) => line.startsWith(`${key}:`)).pipe(
    Option.map((line) => line.slice(key.length + 1).trim().replace(/^(['"])(.*)\1$/, '$2')),
  )
}

// Markdown headings outside fenced code, with the 1-based line each starts on.
const headingsOf = (lines) => {
  const found = []
  let fence = ''
  for (const [i, line] of lines.entries()) {
    const marker = /^ {0,3}(`{3,}|~{3,})(.*)$/.exec(line)
    if (marker) {
      if (!fence) fence = marker[1]
      else if (marker[1][0] === fence[0] && marker[1].length >= fence.length && !marker[2].trim()) fence = ''
      continue
    }
    const heading = fence ? null : /^#{1,6} (.+?)\r?$/.exec(line)
    if (heading) found.push({ name: heading[1], start: i + 1 })
  }
  return found
}

const program = Effect.fn('indexXStateDocs')(function* ({ check }) {
  const fs = yield* FileSystem.FileSystem
  const path = yield* Path.Path
  const repo = path.resolve(yield* path.fromFileUrl(new URL('../', import.meta.url)))
  const manifest = Schema.decodeUnknownSync(Schema.fromJsonString(Schema.Struct({
    dependencies: Schema.Record(Schema.String, Schema.String),
  })))(yield* fs.readFileString(path.join(repo, owner, 'package.json')))

  // The installed copy of a package the owning workspace pins, checked against that pin.
  const installed = Effect.fn('installed')(function* (name) {
    const candidates = [path.join(repo, owner, 'node_modules', name), path.join(repo, 'node_modules', name)]
    const dir = yield* Effect.findFirst(candidates, (dir) => fs.exists(path.join(dir, 'package.json')))
    if (Option.isNone(dir)) return yield* new XStateNotInstalled({ name, message: `${name} is not installed for ${owner}; run bun install` })
    const { version } = Schema.decodeUnknownSync(Schema.fromJsonString(Schema.Struct({ version: Schema.String })))(
      yield* fs.readFileString(path.join(dir.value, 'package.json')),
    )
    const pin = manifest.dependencies[name]
    if (version !== pin) return yield* new XStateNotInstalled({ name, message: `${owner} pins ${name}@${pin} but ${version} is installed; run bun install` })
    return { name, version, dir: dir.value, location: path.relative(repo, dir.value) }
  })

  const xstate = yield* installed('xstate')
  const effect = yield* installed('@xstate/effect')

  const docsDir = path.join(xstate.dir, 'docs')
  const pages = Array.sort(Array.filter(yield* fs.readDirectory(docsDir), (name) => name.endsWith('.md')), Order.String)
  const rows = yield* Effect.forEach(pages, Effect.fn(function* (page) {
    const lines = (yield* fs.readFileString(path.join(docsDir, page))).split('\n')
    const title = Option.getOrElse(frontmatter(lines, 'title'), () => Option.getOrElse(Array.head(headingsOf(lines)), () => ({ name: page })).name)
    const summary = Option.getOrElse(frontmatter(lines, 'description'), () => '')
    return `| [${page}](../../${xstate.location}/docs/${page}) | ${escapeCell(title)} | ${lines.length} | ${escapeCell(summary)} |`
  }))
  const xstateIndex = [
    '# XState documentation index', '',
    'Generated by `scripts/index-xstate-docs.mjs` from the installed package. Do not edit it; `bun run check:xstate-docs` fails when it is stale.', '',
    `${xstate.name}@${xstate.version} ships these pages in \`${xstate.location}/docs/\`, written for that version. Each row is one page; the pages are short, so read the matching page whole. Start with \`index.md\` (reading order), \`agents.md\` (agent guide), and \`xstate-v5-to-v6.md\` (differences from v5). \`docs/api-stability.json\` classifies every export as public, experimental, or internal. Declarations are in \`${xstate.location}/dist/\`.`, '',
    'For Effect-backed actors, see [the @xstate/effect index](../xstate-effect/index.md).', '',
    '| Page | Title | Lines | Summary |', '| --- | --- | ---: | --- |', ...rows, '',
  ].join('\n')

  const readmeLines = (yield* fs.readFileString(path.join(effect.dir, 'README.md'))).split('\n')
  const topics = headingsOf(readmeLines)
  const effectIndex = [
    '# @xstate/effect documentation index', '',
    'Generated by `scripts/index-xstate-docs.mjs` from the installed package. Do not edit it; `bun run check:xstate-docs` fails when it is stale.', '',
    `${effect.name}@${effect.version} documents itself in [README.md](../../${effect.location}/README.md). Line ranges refer to that file; read only the matching range. Declarations are in \`${effect.location}/dist/\`. For XState itself, see [the XState index](../xstate/index.md).`, '',
    '| Topic | Start line | End line |', '| --- | ---: | ---: |',
    ...topics.map((topic, i) => `| ${escapeCell(topic.name)} | ${topic.start} | ${i + 1 < topics.length ? topics[i + 1].start - 1 : readmeLines.length} |`), '',
  ].join('\n')

  const outputs = [
    { file: '.agent-sources/xstate/index.md', text: xstateIndex },
    { file: '.agent-sources/xstate-effect/index.md', text: effectIndex },
  ]
  if (check) {
    const stale = yield* Effect.filter(outputs, ({ file, text }) => fs.readFileString(path.join(repo, file)).pipe(
      Effect.map((current) => current !== text),
      Effect.orElseSucceed(() => true),
    ))
    if (stale.length) {
      const files = Array.map(stale, ({ file }) => file)
      return yield* new StaleXStateIndex({ files, message: `${files.join(', ')} do not match the installed XState packages; run node scripts/index-xstate-docs.mjs` })
    }
    yield* Effect.logInfo(`XState indexes match ${xstate.name}@${xstate.version} and ${effect.name}@${effect.version}`)
    return
  }
  yield* Effect.forEach(outputs, ({ file, text }) => fs.writeFileString(path.join(repo, file), text), { discard: true })
  yield* Effect.logInfo(`Indexed ${rows.length} XState pages and ${topics.length} @xstate/effect topics`)
})

const command = Command.make('index-xstate-docs', {
  check: Flag.Boolean('check').pipe(
    Flag.withDescription('Fail when an index does not match the installed packages'),
    Flag.withDefault(false),
  ),
}, program).pipe(Command.withDescription('Index the documentation the installed XState packages ship'))

command.pipe(
  Command.run({ version: '1.0.0' }),
  Effect.provide([NodeServices.layer, loggerLayer]),
  NodeRuntime.runMain,
)
